def table(df, num_cols=(), fmt=None):
    head = "".join(f'<th class="{"n" if c in num_cols else ""}">{c}</th>' for c in df.columns)
    rows = []
    for _, r in df.iterrows():
        cells = []
        for c in df.columns:
            v = r[c]
            if c in num_cols and not isinstance(v, str):
                v = "–" if pd.isna(v) else (fmt or {}).get(c, lambda x: num(x, 1))(v)
            cells.append(f'<td class="{"n" if c in num_cols else ""}">{v}</td>')
        rows.append("<tr>" + "".join(cells) + "</tr>")
    return f'<table class="t"><tr>{head}</tr>{"".join(rows)}</table>'


def page(title, body):
    return (f'<!doctype html><html lang="ru"><head><meta charset="utf-8"><title>{title}</title>'
            f"<style>{CSS}</style></head><body>{body}</body></html>")


class Fig:
    """Сквозная нумерация рисунков и таблиц в одном документе."""
    def __init__(self):
        self.f = self.t = 0

    def fig(self, img, cap, cls="", src=None):
        self.f += 1
        return (f'<div class="cap">Рисунок {self.f}. {cap}</div><img src="../output/charts/{img}" class="{cls}">'
                f'<div class="src">{src or SRC}</div>')

    def tab(self, cap):
        self.t += 1
        return f'<div class="cap">Таблица {self.t}. {cap}</div>'


